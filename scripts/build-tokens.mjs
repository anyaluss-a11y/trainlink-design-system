import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const data = JSON.parse(readFileSync(resolve(root, 'tokens/figma-export.json'), 'utf8'))
const { Primitives, 'Semantic colors': Semantic, Sizing, Typography } = data.collections

const slug = (name) => name.toLowerCase().replace(/\//g, '-')
const px = (n) => (n === 0 ? '0px' : `${n}px`)

const primitiveNames = new Set(Primitives.map(([name]) => name))
for (const [name, value] of Semantic) {
  if (!primitiveNames.has(value.alias)) throw new Error(`Semantic token "${name}" aliases unknown primitive "${value.alias}"`)
}

const lines = []
const out = (s = '') => lines.push(s)

out('/* GENERATED by scripts/build-tokens.mjs from tokens/figma-export.json — do not edit by hand. */')
out()
out('@theme static {')
out('  /* Colors: primitives, then semantic tokens that alias them */')
out('  --color-*: initial;')
for (const [name, hex] of Primitives) out(`  --color-${slug(name)}: ${hex};`)
out()
for (const [name, { alias }] of Semantic) out(`  --color-${slug(name)}: var(--color-${slug(alias)});`)
out()
out('  /* Radii */')
out('  --radius-*: initial;')
for (const [name, value] of Sizing.radii) out(`  --radius-${name}: ${px(value)};`)
out()
out('  /* Typography */')
out(`  --font-sans: "${Typography.fontFamily.body} Variable", "${Typography.fontFamily.body}", ui-sans-serif, system-ui, sans-serif;`)
out('}')
out()
out(':root {')
out('  /* Spacing, size and border scales (same steps as the Figma Sizing collection) */')
for (const [name, value] of Sizing.spacing) out(`  --space-${name}: ${px(value)};`)
for (const [name, value] of Sizing.size) out(`  --size-${name}: ${px(value)};`)
for (const [name, value] of Sizing.borders) out(`  --border-${name}: ${px(value)};`)
out('}')
out()
out('/* Text styles: one utility per Figma text style, e.g. class="type-body-sm" */')
out(`@source inline("${data.textStyles.map((s) => `type-${slug(s.name)}`).join(' ')}");`)
out()
for (const s of data.textStyles) {
  out(`@utility type-${slug(s.name)} {`)
  out('  font-family: var(--font-sans);')
  out(`  font-weight: ${s.weight};`)
  out(`  font-size: ${px(s.size)};`)
  out(`  line-height: ${s.lh === 'auto' ? 'normal' : typeof s.lh === 'string' ? String(parseFloat(s.lh) / 100) : px(s.lh)};`)
  out(`  letter-spacing: ${s.ls === 0 ? '0' : `${s.ls / 100}em`};`)
  out('}')
  out()
}

const target = resolve(root, 'src/styles/tokens.css')
mkdirSync(dirname(target), { recursive: true })
writeFileSync(target, lines.join('\n'))
console.log(`Wrote ${target}: ${Primitives.length} primitives, ${Semantic.length} semantic colors, ${data.textStyles.length} text styles`)
